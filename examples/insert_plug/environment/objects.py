"""Original STL visuals and cavity-preserving collision models for the task.

The manifest is generated by ``python -m examples.insert_plug.environment.prepare_objects``.
Its vertices are already in metres, upright along +Z, with each object's bottom
at zero. Original STL files remain untouched and are used directly for visuals.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np

from mujoco_tools.paths import WORKSPACE_ROOT


DEFAULT_MANIFEST = "assets/objects/insert_plug/collision.json"


def _values(values) -> str:
    return " ".join(f"{float(value):.12g}" for value in values)


def _path(value: str | Path) -> Path:
    path = Path(value).expanduser()
    return path.resolve() if path.is_absolute() else (WORKSPACE_ROOT / path).resolve()


def _object_data(options: dict, kind: str) -> tuple[dict, Path]:
    manifest_path = _path(options.get("collision_manifest", DEFAULT_MANIFEST))
    with manifest_path.open(encoding="utf-8") as stream:
        manifest = json.load(stream)
    if manifest.get("format_version") != 1 or manifest.get("units") != "metres":
        raise ValueError(f"Unsupported STL collision manifest: {manifest_path}")
    data = manifest[kind]
    source_path = _path(options.get("visual_mesh") or data["source"])
    if hashlib.sha256(source_path.read_bytes()).hexdigest() != data["sha256"]:
        raise ValueError(f"STL differs from its collision manifest: {source_path}. "
                         "Regenerate colliders with python -m examples.insert_plug.environment.prepare_objects")
    # A visual-only transform change would detach it from the measured collider.
    for option, field in (("visual_mesh_scale", "visual_scale"),
                          ("visual_mesh_position", "visual_position"),
                          ("visual_mesh_quaternion", "visual_quaternion")):
        if option in options and not np.allclose(options[option], data[field], rtol=0, atol=1e-10):
            raise ValueError(f"{kind}.{option} must match its collision manifest")
    return data, source_path


def _check_dimension(name: str, configured: float, measured: float) -> None:
    if not np.isclose(configured, measured, rtol=0, atol=1e-8):
        raise ValueError(f"{name}={configured} differs from STL dimension {measured}")


def _add_mesh_assets(assets: ET.Element, data: dict, prefix: str) -> None:
    for part in data["parts"]:
        ET.SubElement(assets, "mesh", name=f"{prefix}_{part['name']}",
                      vertex=_values(np.asarray(part["vertices"]).ravel()),
                      face=" ".join(str(index) for face in part["faces"] for index in face))


def _add_visual(assets: ET.Element, parent: ET.Element, data: dict, path: Path,
                asset_name: str, geom_name: str, colour: str) -> None:
    if assets.find(f"mesh[@name='{asset_name}']") is None:
        ET.SubElement(assets, "mesh", name=asset_name, file=str(path),
                      scale=_values(data["visual_scale"]))
    ET.SubElement(parent, "geom", name=geom_name, type="mesh", mesh=asset_name,
                  pos=_values(data["visual_position"]),
                  quat=_values(data["visual_quaternion"]),
                  contype="0", conaffinity="0", mass="0", group="2", rgba=colour)


def add_board(root: ET.Element, config: dict) -> tuple[float, float]:
    """Add two fixed original holders; return physical cavity floor and rim Z."""
    options = config["board"]
    data, path = _object_data(options, "holder")
    _check_dimension("board.bottom_thickness", options["bottom_thickness"], data["floor_z"])
    _check_dimension("board.wall_height", options["wall_height"], data["rim_z"] - data["floor_z"])
    _check_dimension("board.hole_radius", options["hole_radius"], data["bore_nominal_radius"])
    bottom = float(options["bottom_z"])
    floor, top = bottom + data["floor_z"], bottom + data["rim_z"]
    assets = root.find("asset")
    _add_mesh_assets(assets, data, "holder_collision")
    board = ET.SubElement(root.find("worldbody"), "body", name="socket_board")
    common = {"friction": _values(options["friction"]), "condim": "3",
              "solref": "0.004 1", "solimp": "0.99 0.999 0.0001",
              "contype": "1", "conaffinity": "1", "mass": "0",
              "group": "3", "rgba": "0.3 0.3 0.3 0"}
    for name, colour in (("source", "0.70 0.36 0.12 1"),
                         ("target", "0.10 0.53 0.48 1")):
        xy = options[f"{name}_xy"]
        holder = ET.SubElement(board, "body", name=f"{name}_socket",
                               pos=_values([*xy, bottom]))
        _add_visual(assets, holder, data, path, "holder_visual_asset",
                    f"{name}_holder_visual", colour)
        for part in data["parts"]:
            ET.SubElement(holder, "geom", name=f"{name}_holder_{part['name']}",
                          type="mesh", mesh=f"holder_collision_{part['name']}", **common)
        ET.SubElement(board, "site", name=f"{name}_hole", pos=_values([*xy, top]),
                      size="0.001", rgba="1 1 1 0", group="4")
    return floor, top


def add_peg(root: ET.Element, config: dict, floor: float) -> list[float]:
    """Add a free bolt; its 30 mm shaft is supported by its head on the rim."""
    options = config["peg"]
    data, path = _object_data(options, "bolt")
    for name in ("shaft_radius", "shaft_length", "head_radius", "head_height"):
        _check_dimension(f"peg.{name}", options[name], data[name])
    top = floor + float(config["board"]["wall_height"])
    seated_tip = max(floor, top - data["shaft_length"])
    position = [*config["board"]["source_xy"], seated_tip + options["initial_floor_clearance"]]
    peg = ET.SubElement(root.find("worldbody"), "body", name="peg", pos=_values(position))
    ET.SubElement(peg, "freejoint", name="peg_free")
    assets = root.find("asset")
    _add_visual(assets, peg, data, path, "peg_visual_asset", "peg_visual", "0.75 0.77 0.80 1")
    _add_mesh_assets(assets, data, "peg_collision")
    volumes = np.array([part["volume_m3"] for part in data["parts"]])
    masses = float(options["mass"]) * volumes / volumes.sum()
    for part, mass in zip(data["parts"], masses):
        ET.SubElement(peg, "geom", name=f"peg_{part['name']}_geom", type="mesh",
                      mesh=f"peg_collision_{part['name']}", mass=str(float(mass)),
                      friction=_values(options["friction"]), condim="4",
                      solref="0.004 1", solimp="0.99 0.999 0.0001",
                      contype="1", conaffinity="1", group="3", rgba="0.75 0.77 0.8 0")
    ET.SubElement(peg, "site", name="peg_tip", pos="0 0 0", size="0.001",
                  rgba="1 0 0 0", group="4")
    ET.SubElement(peg, "site", name="peg_head",
                  pos=_values([0, 0, data["shaft_length"] + data["head_height"] / 2]),
                  size="0.001", rgba="0 1 0 0", group="4")
    return position
